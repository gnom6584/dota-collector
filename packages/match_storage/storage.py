from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any


class Storage(ABC):
    """Базовый абстрактный контракт целевого хранилища обогащенных матчей Dota 2.

    Архитектурные принципы:
    1. Изоляция слоя персистентности: конвейер и воркеры ничего не знают о конкретной СУБД,
       файловой системе или формате хранения (SQLite, Parquet, PostgreSQL и др.).
    2. Скользящее кольцевое окно емкости: хранилище поддерживает лимит `max_matches`.
       При достижении максимальной емкости наиболее старые матчи вытесняются (FIFO ring buffer)
       для сохранения актуального среза данных без блокировки конвейера.
    3. Атомарность записи пачки: метод `insert_many` сохраняет переданную пачку матчей
       и возвращает булев результат подтверждения записи.
    """

    @abstractmethod
    def insert_many(self, matches: list[dict[str, Any]]) -> bool:
        """Сохраняет пачку валидных обогащенных матчей в хранилище.

        При достижении максимальной вместимости max_matches автоматически вытесняет
        наиболее старые матчи для освобождения места под актуальные данные.

        Args:
            matches: Список словарей с полными данными обогащенных матчей.

        Returns:
            bool: True при успешной фиксации данных, False при системном сбое записи.
        """
        pass

    @property
    @abstractmethod
    def max_matches(self) -> int:
        """Максимальная вместимость хранилища в количестве матчей."""
        pass

    @abstractmethod
    def set_max_matches(self, max_matches: int) -> None:
        """Обновляет максимальную вместимость хранилища.

        Args:
            max_matches: Новое положительное целочисленное значение вместимости.
        """
        pass

    def get_free_space(self) -> int:
        """Возвращает свободную вместимость хранилища в количестве матчей для телеметрии.

        Returns:
            int: Расчетное количество оставшихся мест до лимита max_matches.
        """
        return max(0, self.max_matches - self.count())

    @abstractmethod
    def count(self) -> int:
        """Возвращает текущее количество сохраненных матчей в хранилище.

        Returns:
            int: Общее число сохраненных матчей.
        """
        pass

    def close(self) -> None:
        """Освобождает дескрипторы и системные ресурсы хранилища."""
        pass
