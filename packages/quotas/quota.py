from __future__ import annotations

from abc import ABC, abstractmethod


class Quota(ABC):
    """Базовый абстрактный контракт контроля и ограничения расхода ресурсов.

    Архитектурные принципы:
    1. Минимализм и чистая абстракция: контракт изолирован от деталей реализации
       (календарные окна, периоды сброса, алгоритмы токенов и персистентность).
    2. Безопасность списания: вызов `acquire()` атомарно проверяет доступность ресурса
       и фиксирует списание без побочных эффектов при исчерпании лимита.
    3. Контроль состояния: предоставляет минимальный набор операций для инспекции остатка
       (`remaining()`), сброса расхода (`reset()`) и освобождения ресурсов (`close()`).
    """

    @property
    @abstractmethod
    def name(self) -> str:
        """Уникальное строковое имя квоты."""
        pass

    @abstractmethod
    def acquire(self, cost: int = 1) -> bool:
        """Атомарно запрашивает списание `cost` единиц ресурса.

        Args:
            cost: Количество запрашиваемых единиц ресурса (должно быть > 0).

        Returns:
            bool: True, если ресурс успешно списан; False, если лимит исчерпан.
        """
        pass

    @abstractmethod
    def remaining(self) -> int:
        """Возвращает доступный остаток ресурса."""
        pass

    @abstractmethod
    def reset(self) -> None:
        """Сбрасывает состояние расхода квоты."""
        pass

    def close(self) -> None:
        """Освобождает внешние ресурсы и дескрипторы при завершении работы."""
        pass
