from __future__ import annotations

from abc import abstractmethod

from .quota import Quota


class DailyQuota(Quota):
    """Абстрактный контракт суточной квоты с календарным расчетным окном (UTC).

    Архитектурные принципы:
    1. Оконная периодичность: привязывает потребление к суточному календарному окну
       с фиксацией временной границы следующего сброса (`reset_at`).
    2. Конфигурируемость емкости: предоставляет методы чтения (`limit`)
       и динамического обновления (`set_limit`) максимального суточного объема.
    3. Учет расхода: предоставляет метод `used()` для инспекции объема потребления
       внутри текущего активного расчетного окна.
    """

    @property
    @abstractmethod
    def limit(self) -> int:
        """Максимальный лимит квоты в текущем суточном окне."""
        pass

    @abstractmethod
    def set_limit(self, limit: int) -> None:
        """Обновляет максимальный лимит суточной квоты.

        Args:
            limit: Новое положительное целочисленное значение лимита.
        """
        pass

    @abstractmethod
    def used(self) -> int:
        """Возвращает израсходованный объем квоты в текущем суточном окне."""
        pass

    @abstractmethod
    def reset_at(self) -> int | None:
        """Возвращает Unix timestamp ближайшей границы сброса суточного окна."""
        pass
