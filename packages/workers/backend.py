from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any

from .status import WorkerStatus


class Backend(ABC):
    """Интерфейс слоя персистентности и координации рантайма воркера.

    Отвечает за изоляцию жизненного цикла воркера от конкретного хранилища
    (SQLite, PostgreSQL, Redis, Memory и т.д.). Разделяет четыре независимых контура:
    1. Контур управления (is_enabled, enable, disable): флаг активности читается раннером,
       но изменяется как раннером, так и извне (через БД, админ-панель или CLI).
    2. Контур статуса (set_status, get_status): фиксация реального состояния
       выполнения (STOPPED, WAITING, SLEEPING, EXECUTING) и PID процесса.
    3. Контур состояния (get_state, set_state): хранение произвольного
       пользовательского стейта воркера между итерациями метода execute().
    4. Контур ошибок (set_error, clear_error): фиксация аварийных ситуаций
       при падении шага и автоматическая очистка при восстановлении работы.

    Требования к реализации:
    - Все методы изолированы по уникальному ключу `worker_name`.
    - `is_enabled`: при отсутствии записи в хранилище должен возвращать False (по умолчанию деактивирован).
    - `enable` / `disable`: атомарно переводят флаг активности воркера в True / False.
    - `set_state` и `set_error`: должны быть идемпотентными (upsert).
    - `clear_error`: удаляет запись об ошибке либо обнуляет её значение.
    - Сериализация произвольного стейта (JSON, BSON, pickle и т.д.) является зоной
      ответственности конкретной имплементации, а не абстрактного интерфейса.
    - `close`: корректно освобождает дескрипторы, транзакции и соединения с БД.
    """

    @abstractmethod
    def is_enabled(self, worker_name: str) -> bool:
        """Проверяет флаг бизнес-активности воркера в хранилище.

        Args:
            worker_name: Уникальный строковый идентификатор воркера.

        Returns:
            True, если воркер явно активирован (is_enabled=1/True);
            False, если воркер деактивирован либо запись в хранилище отсутствует.

        Side-effects:
            Только чтение, не изменяет состояние хранилища.
        """
        pass

    @abstractmethod
    def register_worker(self, worker_name: str, worker_type: str) -> None:
        """Регистрирует сигнатуру типа воркера или валидирует соответствие ранее сохраненной.

        Защищает базу данных от случайной порчи стейта при запуске под тем же именем
        воркера другого класса (Type Fingerprinting).

        Args:
            worker_name: Уникальный строковый идентификатор воркера.
            worker_type: Канонический строковый идентификатор класса (module.QualName).

        Raises:
            TypeError: Если воркер с данным worker_name уже зарегистрирован в БД
                с другим значением worker_type.

        Side-effects:
            Если запись отсутствует — создает строку управления со значением
            is_enabled=False и указанным worker_type.
            Если запись существует с пустым worker_type — привязывает worker_type.
        """
        pass

    @abstractmethod
    def enable(self, worker_name: str) -> None:
        """Переводит флаг бизнес-активности воркера в состояние True.

        Разрешает выполнение итераций execute() в цикле Runner.

        Args:
            worker_name: Уникальный строковый идентификатор воркера.

        Side-effects:
            Атомарный upsert флага is_enabled=1 и отметки updated_at в хранилище.
        """
        pass

    @abstractmethod
    def disable(self, worker_name: str) -> None:
        """Переводит флаг бизнес-активности воркера в состояние False.

        Приостанавливает выполнение execute(), переводя процесс Runner в режим
        периодического опроса (WAITING) без завершения самого процесса ОС.

        Args:
            worker_name: Уникальный строковый идентификатор воркера.

        Side-effects:
            Атомарный upsert флага is_enabled=0 и отметки updated_at в хранилище.
        """
        pass

    @abstractmethod
    def set_status(
        self,
        worker_name: str,
        status: WorkerStatus,
        pid: int | None = None,
    ) -> None:
        """Фиксирует текущее физическое состояние процесса воркера и PID.

        Используется исключительно строго типизированный WorkerStatus (а не произвольный str)
        для обеспечения инварианта конечного автомата состояний рантайма (STOPPED, WAITING,
        SLEEPING, EXECUTING) и защиты от невалидных значений на этапе статического анализа.

        Args:
            worker_name: Уникальный строковый идентификатор воркера.
            status: Канонический статус выполнения из перечисления WorkerStatus.
            pid: Идентификатор процесса ОС (PID) или None при переводе в STOPPED.

        Side-effects:
            Атомарно обновляет статус, PID и отметку времени в записи воркера.
        """
        pass

    @abstractmethod
    def get_status(self, worker_name: str) -> WorkerStatus:
        """Возвращает актуальный физический статус выполнения воркера из хранилища.

        Args:
            worker_name: Уникальный строковый идентификатор воркера.

        Returns:
            Экземпляр WorkerStatus. Если запись в хранилище отсутствует или поле пусто,
            возвращает WorkerStatus.STOPPED.

        Side-effects:
            Только чтение.
        """
        pass

    @abstractmethod
    def get_state(self, worker_name: str, state_cls: Any = None) -> Any:
        """Загружает и десериализует сохраненное состояние воркера.

        Args:
            worker_name: Уникальный строковый идентификатор воркера.
            state_cls: Опциональный класс схемы или типа данных для десериализации
                (например, dataclass, BaseModel или примитивный тип). Если None,
                возвращает десериализованную из JSON структуру (dict/list/примитив).

        Returns:
            Восстановленный объект стейта либо None, если состояние для воркера
            еще ни разу не сохранялось в хранилище.

        Side-effects:
            Только чтение.
        """
        pass

    @abstractmethod
    def set_state(self, worker_name: str, state: Any) -> None:
        """Сериализует и атомарно сохраняет состояние воркера в хранилище.

        Вызывается после каждого успешного завершения шага execute(), а также
        гарантированно при остановке процесса в блоке завершения Runner.

        Args:
            worker_name: Уникальный строковый идентификатор воркера.
            state: Произвольный объект пользовательского состояния воркера.

        Side-effects:
            Идемпотентный upsert сериализованного представления стейта и отметки времени.
        """
        pass

    @abstractmethod
    def set_error(self, worker_name: str, error: str) -> None:
        """Фиксирует информацию о критической ошибке или необработанном исключении воркера.

        Вызывается Runner в модели Fail-Fast перед аварийным выходом для сохранения
        полного трейсбека сбоя и диагностики через инструменты мониторинга.

        Args:
            worker_name: Уникальный строковый идентификатор воркера.
            error: Текстовое описание ошибки или строковый стек-трейс исключения.

        Side-effects:
            Идемпотентный upsert текста ошибки и отметки времени в хранилище.
        """
        pass

    @abstractmethod
    def clear_error(self, worker_name: str) -> None:
        """Удаляет или сбрасывает запись об ошибке воркера.

        Вызывается при ручном сбросе сбоя либо при успешном перезапуске и восстановлении работы.

        Args:
            worker_name: Уникальный строковый идентификатор воркера.

        Side-effects:
            Удаляет запись об ошибке из хранилища.
        """
        pass

    def get_error(self, worker_name: str) -> str | None:
        """Возвращает последнюю зафиксированную ошибку воркера, если она есть.

        Args:
            worker_name: Уникальный строковый идентификатор воркера.

        Returns:
            Строка с описанием ошибки или трейсбеком, либо None при отсутствии ошибки.
        """
        return None

    def get_pid(self, worker_name: str) -> int | None:
        """Возвращает идентификатор процесса ОС (PID) воркера, если он запущен.

        Args:
            worker_name: Уникальный строковый идентификатор воркера.

        Returns:
            PID процесса или None, если процесс не запущен.
        """
        return None

    def get_worker_type(self, worker_name: str) -> str | None:
        """Возвращает зарегистрированный тип воркера.

        Args:
            worker_name: Уникальный строковый идентификатор воркера.

        Returns:
            Строковый идентификатор класса или None, если воркер не зарегистрирован.
        """
        return None

    def get_updated_at(self, worker_name: str) -> str | None:
        """Возвращает отметку времени последнего обновления статуса воркера.

        Args:
            worker_name: Уникальный строковый идентификатор воркера.

        Returns:
            Строка с отметкой времени в UTC или None.
        """
        return None

    def close(self) -> None:
        """Освобождает дескрипторы, транзакции и сетевые/файловые соединения бэкенда.

        Базовая реализация является no-op. Переопределяется в конкретных бэкендах,
        владеющих системными ресурсами или соединениями с базами данных.
        """
        pass
