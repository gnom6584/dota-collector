from __future__ import annotations

from abc import ABC, abstractmethod


class Worker[TState](ABC):
    """Базовый контракт фонового воркера.

    Архитектурные принципы:
    1. Stateless-модель: экземпляр воркера не должен хранить мутирующее состояние
       в `self`. Все изменяемые данные цикла передаются исключительно через аргумент
       `state` и возвращаются в кортеже из метода `execute()`.
    2. Независимость от среды: воркер содержит только чистую бизнес-логику итерации
       и ничего не знает о файловых блокировках, базе данных, перехвате сигналов
       или механизмах ожидания (этим управляет `Runner`).
    3. Идемпотентность и восстановление: при сбое внутри `execute()` предыдущее
       успешное состояние сохраняется в бэкенде, а раннер завершает работу по Fail-Fast модели.

    Правила реализации:
    - `name`: обязательный уникальный строковый идентификатор воркера в системе.
      Используется раннером как ключ для файловой блокировки (PID-lock) и для
      изоляции записей в таблицах бэкенда (`worker_control`, `worker_states`, `worker_errors`).
    - `worker_type`: опциональный явный идентификатор типа воркера для защиты от подмены.
      Если не задан, формируется автоматически как `module.ClassName`.
    - `execute(state)`: атомарное действие одной итерации. Принимает текущий стейт `TState`,
      возвращает кортеж `(обновленный_стейт, секунд_паузы_до_следующего_запуска)`.
    - `close()`: вызывается раннером при остановке процесса (SIGINT/SIGTERM) для
      освобождения ресурсов (HTTP-клиенты, пулы соединений, сокеты).
    """

    name: str
    worker_type: str | None = None

    @abstractmethod
    def execute(self, state: TState) -> tuple[TState, float]:
        """Выполняет одну итерацию бизнес-логики воркера.

        Args:
            state: Актуальное состояние, загруженное раннером из бэкенда (или default_state).

        Returns:
            tuple[TState, float]: Кортеж:
            - Новый стейт, который будет сохранен в бэкенд;
            - Время сна в секундах до следующего вызова execute().
        """
        pass

    def close(self) -> None:
        """Освобождает внешние ресурсы воркера при завершении работы."""
        pass
